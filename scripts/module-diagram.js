#!/usr/bin/env node
// Writes the diagram of the imports between the modules of src/ into
// src/README.md, between the two marker comments. With --check it writes
// nothing and fails when the diagram there differs from the code.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = new URL("../src/", import.meta.url);
const README = new URL("README.md", SRC);
const START = "<!-- module diagram: generated by scripts/module-diagram.js -->";
const END = "<!-- end of module diagram -->";

// The imports between the modules of src/, as [importer, imported] pairs.
function moduleImports() {
  const modules = readdirSync(SRC)
    .filter((f) => f.endsWith(".js"))
    .sort();
  return modules.flatMap((file) => {
    const text = readFileSync(new URL(file, SRC), "utf8");
    return [...text.matchAll(/from\s+"\.\/([\w-]+)\.js"/g)]
      .map((m) => [file.replace(/\.js$/, ""), m[1]])
      .sort();
  });
}

function diagram() {
  // Mermaid reads a hyphen in a node id as part of an arrow, so ids use
  // underscores and show the module name as the label.
  const node = (name) => `${name.replace(/-/g, "_")}["${name}"]`;
  const lines = moduleImports().map(
    ([from, to]) => `  ${node(from)} --> ${node(to)}`,
  );
  return [
    START,
    "",
    "```mermaid",
    "flowchart TD",
    ...lines,
    "```",
    "",
    END,
  ].join("\n");
}

const readme = readFileSync(README, "utf8");
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start < 0 || end < start) {
  console.error("src/README.md: the module diagram markers are missing");
  process.exit(1);
}
const updated =
  readme.slice(0, start) + diagram() + readme.slice(end + END.length);
if (process.argv.includes("--check")) {
  if (updated !== readme) {
    console.error(
      "src/README.md: the module diagram does not match the imports; run: node scripts/module-diagram.js",
    );
    process.exit(1);
  }
} else if (updated !== readme) {
  writeFileSync(README, updated);
  console.log("src/README.md: module diagram updated");
}
